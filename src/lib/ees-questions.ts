type Opt = [string, string, string, string, string];
type Id = EesOption["id"];

function mcq(
  label: string,
  displayNum: number,
  topic: string,
  text: string,
  options: Opt,
  correctId: Id,
  points: number,
  extra?: Partial<EesQuestion>,
): EesQuestion {
  const ids: Id[] = ["A", "B", "C", "D", "E"];
  return {
    label,
    displayNum,
    section: "part1",
    type: "choice",
    topic,
    text,
    points,
    illustration: extra?.illustration ?? null,
    contextNote: extra?.contextNote,
    options: options.map((t, i) => ({ id: ids[i], text: t })),
    correctId,
    solution: extra?.solution ?? `Зөв хариулт: ${correctId}.`,
  };
}

